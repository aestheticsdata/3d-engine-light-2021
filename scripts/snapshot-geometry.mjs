// The geometry baseline: every point and every triangle of all fourteen shapes,
// dumped to disk so a refactor of the generators can be proved to have changed
// nothing.
//
// The layer this guards has no other safety net. A reordered vertex loop, a
// deduped point or a flipped winding does not throw — it recolours a face, or
// moves a number the SHAPE INFO panel prints. A byte-identical dump is the only
// available proof.
//
// It goes through Vite's own build rather than a hand-rolled TypeScript loader
// for two reasons: the registry's imports go through the @data alias, and Vite
// already knows that alias from vite.config.js — so the script cannot drift from
// the app's own resolution. Node's type stripping alone is not enough, because
// `import { Data3D } from "@data/types"` is a type import written in value
// syntax and would fail at runtime with a missing export.
//
// Nothing here touches the DOM, and nothing here imports from src/ui or src/app.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const referenceDir = path.join(root, "notes/oop-refonte/reference");
const baselinePath = path.join(referenceDir, "geometry-baseline.json");
const countsPath = path.join(referenceDir, "geometry-counts.md");

const loadRegistry = async () => {
  const result = await build({
    configFile: path.join(root, "vite.config.js"),
    logLevel: "silent",
    build: {
      ssr: path.join(root, "src/data/data.ts"),
      write: false,
      minify: false,
      target: "esnext",
    },
  });

  const bundles = Array.isArray(result) ? result : [result];
  const code = bundles[0].output[0].code;
  const encoded = Buffer.from(code).toString("base64");
  const registry = await import(`data:text/javascript;base64,${encoded}`);

  return registry.default;
};

// Hand-rolled rather than JSON.stringify's indent, so one point or one triangle
// is one line. Thirty thousand rows indented per element would make a real diff
// unreadable and a spurious one enormous.
const serialise = (registry) => {
  const rows = (values) =>
    values.map((value) => `      ${JSON.stringify(value)}`).join(",\n");

  const shapes = Object.keys(registry).map((key) => {
    const shape = registry[key];

    return [
      `  ${JSON.stringify(key)}: {`,
      `    "points": [`,
      rows(shape.points),
      `    ],`,
      `    "triangles": [`,
      rows(shape.triangles),
      `    ]`,
      `  }`,
    ].join("\n");
  });

  return `{\n${shapes.join(",\n")}\n}\n`;
};

// The same two numbers SHAPE INFO prints, so the panel can be checked against
// the baseline by eye without opening a two-megabyte JSON file.
const countsTable = (registry) => {
  const keys = Object.keys(registry);
  const rows = keys.map(
    (key) =>
      `| ${key} | ${registry[key].points.length} | ${registry[key].triangles.length} |`,
  );

  return [
    "# Geometry counts",
    "",
    "Generated by `pnpm run snapshot:geometry` — do not edit by hand.",
    "",
    "POINTS and TRIANGLES are the registry counts, which is exactly what the",
    "SHAPE INFO panel prints. They are not the drawn-triangle count: that one",
    "follows the renderer and drops as backfaces are culled.",
    "",
    "Registry order, which is also the order the picker lists them in. The first",
    "key is the shape the console boots on.",
    "",
    "| shape | POINTS | TRIANGLES |",
    "| -- | --: | --: |",
    ...rows,
    "",
  ].join("\n");
};

const registry = await loadRegistry();

writeFileSync(baselinePath, serialise(registry));
writeFileSync(countsPath, countsTable(registry));

process.stdout.write(
  `${Object.keys(registry).length} shapes written to ${path.relative(root, baselinePath)}\n`,
);
